"""Core state values shared by runtime and scoring."""

from enum import StrEnum


class RunState(StrEnum):
    PENDING = "PENDING"
    PREPARING = "PREPARING"
    READY = "READY"
    RUNNING = "RUNNING"
    COLLECTING = "COLLECTING"
    SCORING = "SCORING"
    VALIDATING = "VALIDATING"
    COMPLETED = "COMPLETED"
    RETRYABLE_INFRA_FAILURE = "RETRYABLE_INFRA_FAILURE"
    INFRA_INTERRUPTED = "INFRA_INTERRUPTED"
    INVALID_RUN = "INVALID_RUN"
    UNSUPPORTED = "UNSUPPORTED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"
